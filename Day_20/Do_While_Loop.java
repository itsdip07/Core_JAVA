/* 
If my requirnment is to excute the program at least once respective
to the condition , In that case I will use DO_WHILE loop
 */

public class Do_While_Loop {
    public static void main(String[] args) {
        int num = 1;
        do{
            System.out.println(num);
            num++;
        } while (num <= 10);
    }
}
